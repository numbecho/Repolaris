def compile_ui(ui_path: Optional[Path | str] = None, output_path: Optional[Path | str] = None) -> Path:
    """Compiles a Qt Designer .ui file to a native Python module."""
    if ui_path is None:
        ui_path = get_ui_path("app.ui")
    else:
        ui_path = Path(ui_path)

    if not ui_path.exists():
        raise FileNotFoundError(f"UI file not found: {ui_path}")

    if output_path is None:
        output_path = ui_path.parent / f"ui_{ui_path.stem}.py"
    else:
        output_path = Path(output_path)

    # 1. Attempt pyuic6 in PATH
    pyuic_bin = shutil.which("pyuic6")
    if pyuic_bin:
        try:
            res = subprocess.run([pyuic_bin, str(ui_path), "-o", str(output_path)], capture_output=True, text=True, check=True)
            return output_path
        except Exception:
            pass

    # 2. Attempt PyQt6.uic.compileUi
    try:
        from PyQt6 import uic  # type: ignore
        with open(output_path, "w", encoding="utf-8") as f_out:
            uic.compileUi(str(ui_path), f_out)
        return output_path
    except Exception:
        pass

    # 3. Fallback pure-Python compiler
    code = _generate_fallback_code(ui_path)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(code)

    return output_path


if __name__ == "__main__":
    out = compile_ui()
    print(f"Successfully compiled {get_ui_path().name} -> {out.name}")
